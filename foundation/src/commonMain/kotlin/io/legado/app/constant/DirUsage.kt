package io.legado.app.constant

/**
 * 用户选目录时的用途。
 *
 * 受沙盒约束的端 (iOS 的 security-scoped bookmark、鸿蒙的持久化 URI) 按用途登记目录授权:
 * 一条授权只放行同用途的访问 —— 为字体或图片选的宽目录不会放行书籍文件访问, 反之亦然。
 * 同一个目录可为不同用途分别授权 (同一路径在不同用途下各留一条), 两条互不代替。
 *
 * 安卓的系统权限按树 URI 授予、本身没有用途维度, 由应用侧按用途登记选定目录 (AndroidDirAuthorizations)
 * 并在本地书文件访问前校验归属; 桌面为普通文件路径、选定目录不产生系统授权, 无此维度。
 */
enum class DirUsage {
    /** 书籍目录 / 书籍保存位置 / 导入根目录: 本地书文件、备份 zip、导出书籍与日志的读写。 */
    BookTree,

    /**
     * 单文件导出目录: 写出书签/朗读配置/背景配置/规则 json 这类单文件导出成品。
     *
     * 与 [BookTree] 分开: 为导出一个 json 选的宽目录不该顺带放行其下的书籍文件访问。
     */
    Export,

    /** 字体目录: 读取字体文件。 */
    Font,

    /** 图片保存目录: 写出图片。 */
    ImageSave,
}
