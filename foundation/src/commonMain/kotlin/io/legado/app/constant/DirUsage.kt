package io.legado.app.constant

/**
 * 用户选目录时的用途。
 *
 * 受沙盒约束的端 (iOS 的 security-scoped bookmark、鸿蒙的持久化 URI) 按用途登记目录授权:
 * 一条授权只放行同用途的访问 —— 为备份或字体选的宽目录不会放行书籍文件访问, 反之亦然。
 * 同一个目录可为不同用途分别授权 (同一路径在不同用途下各留一条), 两条互不代替。
 *
 * 安卓的 SAF 权限按树 URI 授予、桌面为普通文件路径, 均无用途维度, 忽略本类型。
 */
enum class DirUsage {
    /** 书籍目录 / 书籍保存位置 / 导入根目录: 本地书文件的读取、写入与删原文件。 */
    BookTree,

    /** 导出目录: 写出导出成品。 */
    Export,

    /** 备份目录: 写出备份文件。 */
    Backup,

    /** 字体目录: 读取字体文件。 */
    Font,

    /** 图片保存目录: 写出图片。 */
    ImageSave,
}
